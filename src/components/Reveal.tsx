"use client";

import { useEffect, useRef, useState } from "react";

// Envuelve cualquier contenido y le agrega un fade-in + leve desplazamiento
// hacia arriba cuando entra en el viewport (scroll reveal). Se usa alrededor
// de secciones completas y de tarjetas individuales (con `delay` para
// escalonar la entrada). Respeta prefers-reduced-motion vía la clase
// `.reveal` definida en globals.css.
export default function Reveal({
  children,
  delay = 0,
  className = "",
}: {
  children: React.ReactNode;
  delay?: number;
  className?: string;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;

    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setVisible(true);
          observer.disconnect();
        }
      },
      { threshold: 0.15, rootMargin: "0px 0px -60px 0px" }
    );

    observer.observe(el);
    return () => observer.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      className={`reveal ${visible ? "reveal-visible" : ""} ${className}`}
      style={{ transitionDelay: visible ? `${delay}ms` : "0ms" }}
    >
      {children}
    </div>
  );
}
